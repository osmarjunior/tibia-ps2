#!/usr/bin/env python3
"""
Extract sprites from Tibia 7.4 .spr file into a C header for PS2 embedding.

Usage:
    python extract_sprites.py Tibia.spr sprite_id1 sprite_id2 ... > spr_data_gen.h

Format (from otclient/src/client/spritemanager.cpp):
    Header:
        uint32: signature
        uint16: sprite count        (old versions < 1281)
    Offset table (starts at byte 6):
        uint32[]: sprite offset for id N is at (N-1)*4 + 6
    Each sprite (at its offset):
        byte[3]: RGB color key      (skipped)
        uint16: compressed data size
        byte[size]: compressed pixel data
    Decompression (RLE):
        (uint16 transparent, uint16 colored) pairs
        Colored pixels: 3 bytes RGB each (alpha = 255)
"""
import struct
import sys

SPRITE_SIZE = 32
PIXELS_PER_SPRITE = SPRITE_SIZE * SPRITE_SIZE


def decode_sprite(data, sprite_offset):
    """Decode one sprite. Returns list of (r,g,b,a) tuples (1024 pixels)."""
    if sprite_offset == 0 or sprite_offset >= len(data):
        return None

    # Skip 3 bytes RGB color key
    pos = sprite_offset + 3

    # Read compressed data size (uint16)
    pixel_data_size = struct.unpack_from('<H', data, pos)[0]
    pos += 2

    compressed = data[pos : pos + pixel_data_size]

    pixels = []
    cpos = 0
    while cpos + 4 <= pixel_data_size and len(pixels) < PIXELS_PER_SPRITE:
        transparent, colored = struct.unpack_from('<HH', compressed, cpos)
        cpos += 4

        # Transparent pixels (alpha = 0)
        for _ in range(transparent):
            pixels.append((0, 0, 0, 0))

        # Colored pixels: 3 bytes RGB each (alpha = 255)
        for _ in range(colored):
            if cpos + 3 > pixel_data_size:
                break
            r, g, b = compressed[cpos], compressed[cpos+1], compressed[cpos+2]
            pixels.append((r, g, b, 255))
            cpos += 3

    # Pad remaining as transparent
    while len(pixels) < PIXELS_PER_SPRITE:
        pixels.append((0, 0, 0, 0))

    return pixels[:PIXELS_PER_SPRITE]


def pixels_to_c(pixels, name):
    """Convert pixel list to C array (RGBA interleaved bytes)."""
    lines = [f"static const unsigned char {name}[{PIXELS_PER_SPRITE * 4}] = {{"]
    for i in range(0, len(pixels), 4):
        row = pixels[i:i+4]
        hexes = ", ".join(f"0x{r:02X},0x{g:02X},0x{b:02X},0x{a:02X}" for r, g, b, a in row)
        lines.append(f"    {hexes},")
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} Tibia.spr sprite_id1 sprite_id2 ...", file=sys.stderr)
        sys.exit(1)

    spr_path = sys.argv[1]
    sprite_ids = [int(x) for x in sys.argv[2:]]

    with open(spr_path, 'rb') as f:
        data = f.read()

    # Header
    signature = struct.unpack_from('<I', data, 0)[0]
    sprite_count = struct.unpack_from('<H', data, 4)[0]
    sprites_offset = 6  # offset table starts right after 4-byte signature + 2-byte count

    print(f"/* Generated by extract_sprites.py */")
    print(f"/* Source: {spr_path} */")
    print(f"/* Signature: 0x{signature:08X}, Sprites: {sprite_count} */")
    print(f"#ifndef SPR_DATA_GEN_H")
    print(f"#define SPR_DATA_GEN_H")
    print()
    print(f"#define SPRITE_SIZE {SPRITE_SIZE}")
    print(f"#define PIXELS_PER_SPRITE {PIXELS_PER_SPRITE}")
    print(f"#define SPRITE_BYTES ({PIXELS_PER_SPRITE * 4})")
    print(f"#define NUM_EXTRACTED_SPRITES {len(sprite_ids)}")
    print()

    valid_ids = []
    for sprite_id in sprite_ids:
        if sprite_id < 1 or sprite_id > sprite_count:
            print(f"/* WARNING: sprite ID {sprite_id} out of range (1..{sprite_count}) */")
            continue

        # Offset for sprite id N is at (N-1)*4 + sprites_offset
        offset_pos = (sprite_id - 1) * 4 + sprites_offset
        sprite_offset = struct.unpack_from('<I', data, offset_pos)[0]

        if sprite_offset == 0:
            print(f"/* WARNING: sprite ID {sprite_id} has zero offset (unused) */")
            continue

        pixels = decode_sprite(data, sprite_offset)
        if pixels is None:
            print(f"/* WARNING: failed to decode sprite ID {sprite_id} */")
            continue

        # Count non-transparent pixels for debug info
        opaque = sum(1 for p in pixels if p[3] > 0)
        name = f"sprite_{sprite_id}"
        print(f"/* Sprite ID {sprite_id}, file offset {sprite_offset}, {opaque}/{PIXELS_PER_SPRITE} opaque pixels */")
        print(pixels_to_c(pixels, name))
        print()
        valid_ids.append(sprite_id)

    # Emit ID table
    print(f"#define NUM_VALID_SPRITES {len(valid_ids)}")
    print()
    print(f"static const unsigned char *SPRITE_DATA[NUM_VALID_SPRITES] = {{")
    for sid in valid_ids:
        print(f"    sprite_{sid},")
    print("};")
    print()
    print(f"static const int SPRITE_IDS[NUM_VALID_SPRITES] = {{")
    for sid in valid_ids:
        print(f"    {sid},")
    print("};")
    print()
    print(f"/* Map Tibia spriteId -> texture index */")
    print(f"static int sprite_id_to_index(int tibia_id) {{")
    print(f"    for (int i = 0; i < NUM_VALID_SPRITES; i++) {{")
    print(f"        if (SPRITE_IDS[i] == tibia_id) return i;")
    print(f"    }}")
    print(f"    return -1;")
    print(f"}}")
    print()
    print("#endif /* SPR_DATA_GEN_H */")


if __name__ == '__main__':
    main()
